static bool fb[PANEL_ROWS][PANEL_COLS];

int panel_init(void)
{
	if (!spi_is_ready_dt(&spi) || !pwm_is_ready_dt(&en)) {
		return -ENODEV;
	}

	/* Clear the shift registers before enabling the outputs */
	panel_brightness(0);
	panel_clear();
	return panel_show();
}

void panel_clear(void)
{
	memset(fb, 0, sizeof(fb));
}

void panel_set(int x, int y, bool on)
{
	if (x >= 0 && x < PANEL_COLS && y >= 0 && y < PANEL_ROWS) {
		fb[y][x] = on;
	}
}

int panel_show(void)
{
	uint8_t bits[PANEL_ROWS * PANEL_COLS / 8] = {0};

	for (int i = 0; i < PANEL_ROWS * PANEL_COLS; i++) {
		uint8_t p = positions[i];

		if (fb[p / PANEL_COLS][p % PANEL_COLS]) {
			bits[i / 8] |= 0x80 >> (i % 8);
		}
	}

	const struct spi_buf buf = {.buf = bits, .len = sizeof(bits)};
	const struct spi_buf_set tx = {.buffers = &buf, .count = 1};

	/* CS (CLA) is low while shifting and goes high afterwards, latching the frame */
	return spi_write_dt(&spi, &tx);
}

int panel_brightness(uint8_t percent)
{
	return pwm_set_pulse_dt(&en, en.period * percent / 100);
}
