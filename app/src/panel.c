/*
 * The panel is a chain of four SCT2024 16-bit shift registers. A frame is
 * 256 bits shifted in MSB first; the order in which the LEDs are chained is
 * described by positions[] (taken from github.com/ph1p/ikea-led-obegraensad).
 */

#include <string.h>
#include <zephyr/kernel.h>
#include <zephyr/drivers/spi.h>
#include <zephyr/drivers/pwm.h>

#include "panel.h"

#define PANEL DT_NODELABEL(obegraensad)

static const struct spi_dt_spec spi =
	SPI_DT_SPEC_GET(PANEL, SPI_OP_MODE_MASTER | SPI_WORD_SET(8) | SPI_TRANSFER_MSB);
static const struct pwm_dt_spec en = PWM_DT_SPEC_GET(PANEL);

